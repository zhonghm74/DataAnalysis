@functools.lru_cache(maxsize=512)
def get_stock_name(code: str) -> str:
    """Get stock name by code. Returns code itself if not found."""
    if code in _BUILTIN_NAMES:
        return _BUILTIN_NAMES[code]

    # Fallback: try fetching from akshare (single stock)
    try:
        import akshare as ak
        df = ak.stock_zh_a_hist(symbol=code, period="daily",
                                 start_date="20260101", end_date="20260301", adjust="qfq")
        if len(df) > 0:
            return code  # akshare hist doesn't return name, just return code
    except Exception:
        pass
    return code


def format_stock(code: str) -> str:
    """Format as 'CODE NAME' for display."""
    name = get_stock_name(code)
    return f"{code} {name}" if name != code else code


def format_stock_html(code: str) -> str:
    """Format as HTML with name in gray."""
    name = get_stock_name(code)
    if name != code:
        return f"{code} <span style='color:gray;font-size:0.9em'>{name}</span>"
    return code
